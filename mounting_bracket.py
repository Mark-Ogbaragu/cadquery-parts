import cadquery as cq

bracket = (
    cq.Workplane("XY")
    .box(60, 40, 5)
    .faces(">Z")
    .workplane()
    .pushPoints([
        (-25, -15),
        (25, -15),
        (-25, 15),
        (25, 15),
    ])
    .hole(6)
)

bracket = (
    bracket
    .faces(">Z")
    .workplane()
    .rect(30, 15)
    .cutThruAll()
)

cq.exporters.export(bracket, "mounting_bracket.stl")
cq.exporters.export(bracket, "mounting_bracket.step")

print("Done! Bracket created: 60x40x5mm, 4x 6mm holes, center cutout")
print(f"Volume: {bracket.val().Volume():.1f} mm3")

